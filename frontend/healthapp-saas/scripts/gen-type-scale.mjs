// Generates src/type-scale.css for each app: maps the tiny font sizes in styles.css (6-11px)
// onto a clean scale (11px caption, 12px small). Larger sizes are left alone.
// Usage: node scripts/gen-type-scale.mjs
import postcss from 'postcss';
import fs from 'node:fs';
const map=v=>v<=9?11:v<=11?12:null;
for(const app of ['outlet','customer','admin','broccoly']){
  const dir=`apps/${app}-web/src/`;
  const root=postcss.parse(fs.readFileSync(dir+'styles.css','utf8'));
  const seen=new Set(),out=[];
  root.walkDecls('font-size',d=>{
    const m=/^([\d.]+)px$/.exec(d.value.trim()); if(!m) return;
    const to=map(parseFloat(m[1])); if(to===null) return;
    const chain=[]; let p=d.parent, ok=true;
    while(p&&p.type!=='root'){ if(p.type==='atrule'){ if(/keyframes$/.test(p.name)){ok=false;break} chain.unshift(`@${p.name} ${p.params}`)} p=p.parent }
    if(!ok||d.parent.type!=='rule') return;
    const rule=`${d.parent.selector}{font-size:${to}px}`;
    const key=chain.join('|')+'|'+rule; if(seen.has(key)) return; seen.add(key);
    out.push(chain.reduceRight((inner,c)=>`${c}{${inner}}`,rule));
  });
  fs.writeFileSync(dir+'type-scale.css','/* GENERATED by scripts/gen-type-scale.mjs. Do not edit. */\n'+out.join('\n')+'\n');
  console.log(app,out.length,'rules');
}
